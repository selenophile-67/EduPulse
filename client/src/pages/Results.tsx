import { useQuery } from '@tanstack/react-query';
import { Link } from 'react-router-dom';
import { ArrowRight, BadgeCheck, Quote, Star, Trophy, Users } from 'lucide-react';
import { api, errorMessage } from '../lib/api';
import { Avatar, ErrorState, PageLoader, Progress, SectionHeading } from '../components/ui';
import { formatDate, percent } from '../lib/format';

interface PublicResult {
  studentName: string;
  avatarColor: string;
  score: number;
  maxMarks: number;
  percent: number;
  accuracy: number;
  testTitle: string;
  exam: string;
  createdAt: string;
}

interface SuccessStory {
  name: string;
  avatar_color: string;
  course_title: string;
  exam: string;
  rating: number;
  body: string;
}

interface PublicResults {
  results: PublicResult[];
  successStories: SuccessStory[];
}

export function ResultsPage() {
  const { data, isLoading, error, refetch } = useQuery({
    queryKey: ['public-results'],
    queryFn: () => api.get<PublicResults>('/tests/public-results'),
  });

  if (isLoading) return <div className="container-x"><PageLoader label="Loading results" /></div>;
  if (error || !data) {
    return <div className="container-x py-16"><ErrorState message={errorMessage(error)} onRetry={() => refetch()} /></div>;
  }

  return (
    <div className="bg-page">
      <section className="relative overflow-hidden border-b border-line bg-navy text-white">
        <div className="bg-grid absolute inset-0 opacity-[0.12]" />
        <div className="container-x relative py-12 lg:py-16">
          <span className="inline-flex items-center gap-2 rounded-full border border-white/15 bg-white/5 px-3 py-1.5 text-[11px] font-semibold text-white/80">
            <Trophy size={12} /> Verified results
          </span>
          <h1 className="mt-4 max-w-3xl font-display text-3xl font-extrabold tracking-tight sm:text-4xl">
            Real scores from real attempts.
          </h1>
          <p className="mt-3 max-w-2xl text-sm leading-relaxed text-white/65 sm:text-base">
            This board reads directly from submitted test attempts. Only server-scored results appear — no screenshots, no invented ranks, no inflated toppers.
          </p>
        </div>
      </section>

      <div className="container-x py-8 lg:py-10">
        <div className="grid gap-8 lg:grid-cols-[1fr_340px]">
          <section>
            <SectionHeading eyebrow="Latest toppers" title="Top scores this season" description="Ranked by percentage within each test. Ranks shown elsewhere are cohort-specific." />
            {data.results.length === 0 ? (
              <div className="card p-10 text-center text-sm text-ink-muted">No submitted results yet. Be the first to attempt a test.</div>
            ) : (
              <div className="space-y-3">
                {data.results.map((result, index) => (
                  <div key={`${result.studentName}-${result.createdAt}`} className="card flex flex-wrap items-center gap-3 p-4">
                    <span className={`flex h-8 w-8 items-center justify-center rounded-full text-xs font-bold ${index < 3 ? 'bg-amber-100 text-amber-700 dark:bg-amber-500/15 dark:text-amber-300' : 'bg-surface-2 text-ink-muted'}`}>
                      {index + 1}
                    </span>
                    <Avatar name={result.studentName} color={result.avatarColor} size={38} />
                    <div className="min-w-0 flex-1">
                      <p className="truncate text-sm font-semibold text-ink">{result.studentName}</p>
                      <p className="truncate text-[11px] text-ink-muted">{result.testTitle} · {result.exam} · {formatDate(result.createdAt)}</p>
                      <div className="mt-1.5 max-w-xs">
                        <Progress value={result.percent} size="sm" tone={result.percent >= 60 ? 'success' : 'brand'} />
                      </div>
                    </div>
                    <div className="flex items-center gap-5 text-right">
                      <div>
                        <p className="text-sm font-bold text-ink">{result.score}/{result.maxMarks}</p>
                        <p className="text-[10px] text-ink-muted">{result.percent}%</p>
                      </div>
                      <div>
                        <p className="text-sm font-bold text-ink">{percent(result.accuracy)}</p>
                        <p className="text-[10px] text-ink-muted">Accuracy</p>
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            )}

            <div className="card mt-6 flex items-start gap-3 p-4">
              <BadgeCheck size={18} className="mt-0.5 shrink-0 text-success" />
              <p className="text-xs leading-relaxed text-ink-muted">
                Results are generated by the scoring engine the moment an attempt is submitted. Accuracy counts only attempted questions; negative marking is included in the score.
              </p>
            </div>
          </section>

          <aside className="space-y-4">
            <div className="card p-5">
              <p className="flex items-center gap-2 text-sm font-semibold text-ink"><Star size={15} className="text-amber-400" /> Student stories</p>
              <div className="mt-4 space-y-4">
                {data.successStories.length === 0 ? (
                  <p className="text-xs leading-relaxed text-ink-muted">No written reviews yet. Enrolled students can share one on the course page.</p>
                ) : (
                  data.successStories.map((story) => (
                    <div key={`${story.name}-${story.course_title}`} className="border-b border-line pb-4 last:border-0 last:pb-0">
                      <Quote size={14} className="text-brand" />
                      <p className="mt-1 text-xs leading-relaxed text-ink-soft">{story.body}</p>
                      <div className="mt-2 flex items-center gap-2">
                        <Avatar name={story.name} color={story.avatar_color} size={22} />
                        <div>
                          <p className="text-[11px] font-semibold text-ink">{story.name}</p>
                          <p className="text-[10px] text-ink-muted">{story.course_title}</p>
                        </div>
                      </div>
                    </div>
                  ))
                )}
              </div>
            </div>

            <div className="card bg-navy p-5 text-white">
              <p className="flex items-center gap-2 text-sm font-semibold"><Users size={15} className="text-brand" /> Want your name here?</p>
              <p className="mt-1.5 text-xs leading-relaxed text-white/60">Take a free full-length test and review every solution afterwards.</p>
              <Link to="/tests" className="mt-3 inline-flex items-center gap-1 text-xs font-semibold text-brand">Browse test series <ArrowRight size={12} /></Link>
            </div>
          </aside>
        </div>
      </div>
    </div>
  );
}
